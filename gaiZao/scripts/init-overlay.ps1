# init-overlay.ps1 - regenerate gaiZao/overlays/cordis.patch.yml.
#
#   powershell -NoProfile -ExecutionPolicy Bypass -File gaiZao/scripts/init-overlay.ps1
#
# VelAgent features ship as profile bundles (dsh plugin add), so no host-plugin rows
# are needed yet. Host-plugin features would append their rows here.
$ErrorActionPreference = 'Stop'
$scriptsDir = Split-Path -Parent $MyInvocation.MyCommand.Path
$repoRoot = Split-Path -Parent (Split-Path -Parent $scriptsDir)
$overlay = Join-Path $repoRoot 'gaiZao\overlays\cordis.patch.yml'
$features = Get-ChildItem (Join-Path $repoRoot 'gaiZao\features') -Directory |
  Where-Object { Test-Path (Join-Path $_.FullName 'cordis.patch.yml') } |
  Select-Object -ExpandProperty Name

$lines = @(
  '# generated by gaiZao/scripts/init-overlay.ps1 - do not edit by hand',
  '# bundle features mount through the profile bundle list (dsh plugin add).',
  '# host-plugin rows would be appended here.',
  '[]'
)
Set-Content -Path $overlay -Value ($lines -join [Environment]::NewLine)
Write-Host ('overlay regenerated for features: ' + ($features -join ', '))
